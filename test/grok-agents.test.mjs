import {test} from 'node:test';import assert from 'node:assert/strict';import fs from 'node:fs/promises';import os from 'node:os';import path from 'node:path';import {spawn} from 'node:child_process';
test('Grok Build 智能体：Markdown 解析、增删改、冲突保护与符号链接限制',async()=>{
 const home=await fs.mkdtemp(path.join(os.tmpdir(),'bobo-grok-agents-')),agentDir=path.join(home,'.grok','agents');
 await fs.mkdir(path.join(agentDir,'team'),{recursive:true});
 await fs.writeFile(path.join(agentDir,'reviewer.md'),'---\nname: reviewer\ndescription: >\n  Reviews changes\n  carefully.\nprompt_mode: full\npermission_mode: plan\n---\n\nReview code like an owner.\n');
 await fs.writeFile(path.join(agentDir,'team','nested.md'),'---\nname: nested\ndescription: Nested agent\n---\n\nDo nested things.\n');
 await fs.writeFile(path.join(agentDir,'broken.md'),'---\nname: other\n---\n\nMissing description.\n');
 await fs.writeFile(path.join(home,'outside.md'),'---\nname: outside\ndescription: Outside\n---\n\nOutside.\n');
 await fs.symlink(path.join(home,'outside.md'),path.join(agentDir,'linked.md'));
 await fs.writeFile(path.join(home,'package.json'),'{"type":"module"}');
 const port=14362;const child=spawn(process.execPath,['../src/server.mjs'],{cwd:import.meta.dirname,env:{...process.env,BOBO_HOME:home,GROK_HOME:path.join(home,'.grok'),PORT:String(port)},stdio:'pipe'});
 try{
  await new Promise((resolve,reject)=>{child.stdout.once('data',resolve);child.once('error',reject);child.once('exit',c=>reject(Error('server exit '+c)));});
  const base='http://127.0.0.1:'+port,html=await(await fetch(base)).text(),token=html.match(/name="token" content="([^"]+)"/)[1];
  const req=async(route,data)=>{const r=await fetch(base+'/api/'+route,{method:data?'POST':'GET',headers:{'x-bobo-token':token,'Content-Type':'application/json'},body:data?JSON.stringify(data):undefined});return {status:r.status,data:await r.json()};};
  assert.equal((await fetch(base+'/api/grok/agents')).status,403);
  const list=(await req('grok/agents')).data,byId=Object.fromEntries(list.agents.map(a=>[a.id,a]));
  assert.equal(list.root,agentDir);
  assert.deepEqual(Object.keys(byId).sort(),['broken','linked','reviewer','team/nested']);
  assert.equal(byId.reviewer.name,'reviewer');assert.equal(byId.reviewer.description,'Reviews changes carefully.');
  assert.equal(byId.reviewer.promptMode,'full');assert.equal(byId.reviewer.permissionMode,'plan');
  assert.ok(byId.broken.problems.some(p=>p.includes('description')));
  assert.ok(byId.broken.problems.some(p=>p.includes('name')));
  assert.equal(byId.linked.link,true);
  const created=await req('grok/agents/create',{id:'writer',description:'Writes docs: carefully'});
  assert.equal(created.status,200);
  const text=await fs.readFile(path.join(agentDir,'writer.md'),'utf8');
  assert.match(text,/^name: writer$/m);assert.match(text,/^description: "Writes docs: carefully"$/m);
  assert.equal((await req('grok/agents/create',{id:'writer'})).status,409);
  assert.equal((await req('grok/agents/create',{id:'Bad Name'})).status,400);
  const f=(await req('grok/agents/file?id=reviewer')).data;
  assert.match(f.content,/Review code/);
  assert.equal((await req('grok/agents/save',{id:'reviewer',content:'x',version:'old'})).status,409);
  const saved=await req('grok/agents/save',{id:'reviewer',content:f.content+'\n# more',version:f.version});
  assert.equal(saved.status,200);await fs.access(path.join(saved.data.backup,'manifest.json'));
  assert.equal((await req('grok/agents/file?id=../outside')).status,400);
  assert.equal((await req('grok/agents/save',{id:'linked',content:'x',version:'y'})).status,400);
  assert.equal((await req('grok/agents/rename',{id:'writer',next:'team/writer'})).status,200);
  await fs.access(path.join(agentDir,'team','writer.md'));
  assert.equal((await req('grok/agents/delete',{id:'team/writer'})).status,200);
  assert.equal((await req('grok/agents/delete',{id:'missing-one'})).status,404);
  const aiDoc=await req('ai/grok/document?id=reviewer');
  assert.equal(aiDoc.status,200);assert.ok(aiDoc.data.blocks.length>0);
  assert.equal((await req('ai/grok/document?id=missing-one')).status,404);
  const providers=(await req('configs/providers')).data.providers;
  assert.equal(providers.find(p=>p.id==='grok').agents,'grok');
  assert.equal(providers.find(p=>p.id==='grok').skillAgent,'grok');
 }finally{child.kill();await new Promise(r=>child.once('exit',r));await fs.rm(home,{recursive:true,force:true});}
});
